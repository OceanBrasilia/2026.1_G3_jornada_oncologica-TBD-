/**
 * Traduz um campo para um rótulo legível: usa o dicionário acima quando
 * existe; senão, tenta "arrumar" o nome bruto (snake_case/camelCase),
 * só como última alternativa.
 */
export function formatarLabelCampo(campo: string): string {
  if (FIELD_LABELS[campo]) return FIELD_LABELS[campo];
  if (/[ /()]/.test(campo)) return campo; // já parece um rótulo de verdade
  let s = campo
    .replace(/_/g, " ")
    .replace(/([a-zà-ú])([A-ZÀ-Ú])/g, "$1 $2")
    .replace(/\s+/g, " ")
    .trim();
  return s.charAt(0).toUpperCase() + s.slice(1);
}
